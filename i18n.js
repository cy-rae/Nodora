let uiLang = "en";

function matchLanguage(list) {
  for (const raw of list) {
    const code = String(raw || "").toLowerCase().split("-")[0];
    if (LANGS.includes(code)) return code;
  }
  return "en";
}

function detectLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch (err) {
    /* private mode */
  }
  const list = navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language || "en"];
  return matchLanguage(list);
}

function t(key, vars) {
  const pack = I18N[uiLang] || I18N.en;
  let text = pack[key];
  if (text == null) text = I18N.en[key];
  if (text == null) return key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

function applyStaticI18n() {
  document.documentElement.lang = uiLang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}

function renderLangSwitch() {
  const root = document.getElementById("lang-switch");
  if (!root) return;
  root.setAttribute("aria-label", t("aria.language"));
  root.innerHTML = LANG_META.map((lang) => {
    const on = lang.id === uiLang ? "true" : "false";
    return `<button type="button" class="lang-btn" role="radio" data-lang="${lang.id}" aria-checked="${on}"><span class="lang-flag">${FLAGS[lang.id]}</span><span class="lang-name">${lang.label}</span></button>`;
  }).join("");
}
